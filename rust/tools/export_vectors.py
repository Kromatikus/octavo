#!/usr/bin/env python3
"""Export the published Octavo vectors to one flat JSON file for the Rust tests.

Reads (never writes) this repo's score/vectors.json (score v11, 79 vectors),
score/app_vectors.json (6 app vectors) and the three live sample files (or the
tree in $OCTAVO_PY_DIR / a path argument). Every message is materialised as hex
and every implied field (rounds, chunk size, pickup, nonce) is made explicit,
so the Rust side needs no generator logic. Output: vectors/octavo_vectors.json
"""
import hashlib, json, os, re, sys
from pathlib import Path
sys.dont_write_bytecode = True
sys.path.insert(0, str(Path(__file__).resolve().parent))
from octavo_ref import py_dir

SRC = sys.argv[1] if len(sys.argv) > 1 else str(py_dir())
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))), 'vectors', 'octavo_vectors.json')
V = json.load(open(os.path.join(SRC, 'score', 'vectors.json')))
A = json.load(open(os.path.join(SRC, 'score', 'app_vectors.json')))

# Message generators as published in score/README.md (same table as independent_check/run_check.py)
MSGS = {'0': b'', '1': b'A', '127': bytes(range(127)), '128': bytes(range(128)),
        '1000': bytes((i * 3 + 1) % 256 for i in range(1000)), '4096': bytes((i * 7 + 13) % 256 for i in range(4096)),
        '70000': bytes((i * 11 + 5) % 256 for i in range(70000)), '11': b'hello world'}

def msg_for(v):
    if 'msg' in v and len(v['msg']) // 2 == v.get('msg_len', len(v['msg']) // 2):
        m = bytes.fromhex(v['msg'])
    else:
        m = MSGS[str(v['msg_len'])]
    if 'msg_sha256' in v:
        assert hashlib.sha256(m).hexdigest() == v['msg_sha256'], v['id']
    return m

ROUNDS_BLOCK = {130: 2, 132: 4, 134: 6, 144: 16, 6: 16}
ROUNDS_MOV = {131: 2, 133: 4, 135: 6, 145: 16, 7: 16}

def flat(sec, seed_name, v):
    m = msg_for(v); mode = v['mode']
    o = dict(section=sec, id=v['id'], mode=mode, seed=seed_name, ad=v['ad'], msg=m.hex(),
             pickup=v['pickup'] if 'pickup' in v else v['blob'][8:40],
             fmt_version=v['fmt_version'], blob_len=v['blob_len'], blob_sha256=v['blob_sha256'])
    if 'blob' in v and len(v['blob']) // 2 == v['blob_len']:
        o['blob'] = v['blob']
    if mode in ('block', 'etude-block'):
        o['rounds'] = v.get('rounds') or ROUNDS_BLOCK[v['fmt_version']]
    elif mode in ('movements', 'etude-movements'):
        o['rounds'] = v.get('rounds') or ROUNDS_MOV[v['fmt_version']]
    elif mode == 'rehearsal':
        o['rounds'] = 16
        o['nonce'] = v['nonce'] if 'nonce' in v else v['blob'][40:72]
        o['chunk_size'] = v.get('chunk_size') or int(v['id'].split('cs')[-1])
        if 'final_tag' in v: o['final_tag'] = v['final_tag']
    else:
        raise SystemExit('unknown mode ' + mode)
    return o

seed = V['seed']['hex']; nd = V['nondemo']; nseed = nd['seed']['hex']
assert hashlib.sha256(bytes.fromhex(seed)).hexdigest() == V['seed']['sha256']
assert bytes.fromhex(nseed) == hashlib.shake_256(b"Octavo published non-demo test seed v1").digest(128)

out = dict(
    note='Flat export of Octavo score v%d (%s) + app vectors + live samples. Generated by tools/export_vectors.py; '
         'source files unchanged. Octavo is still homemade; for real secrets use AES-GCM-SIV, age, or libsodium.'
         % (V['score_version'], V['revision']),
    sneak_n2_sha256=V['sneak_n2_sha256'],
    seeds=dict(demo=seed, nondemo=nseed),
    sigs=dict(demo=dict(key_sig=V['key_sig'], rehearsal_sig=V['rehearsal_sig']),
              nondemo=dict(key_sig=nd['key_sig'], rehearsal_sig=nd['rehearsal_sig'])),
    etude_key_sha256=V['format']['etude_key_sha256'],
    block_cipher=[dict(id=v['id'], rounds=v['rounds'], nonce=v['nonce'], plaintext=v['plaintext'], ciphertext=v['ciphertext'])
                  for v in V['block_cipher']],
    formats=[flat(sec, 'demo', v) for sec in ('aead', 'movements', 'rehearsal') for v in V[sec]]
            + [flat('nondemo', 'nondemo', v) for v in nd['vectors']],
    app_keys=[dict(id=k['id'], key=k['key'], seed=k['seed']) for k in A['keys']],
    app_blobs=[dict(id=b['id'], key_id=b['key_id'], blob=b['blob'], ad=b.get('ad_hex', ''), msg=b['msg_hex']) for b in A['blobs']],
)

def sample(f):
    return re.search(r'^blob .*?: ([0-9a-f]{100,})$', open(os.path.join(SRC, f)).read(), re.M).group(1)
out['samples'] = [dict(id='hello-world.txt', mode='block', ad='', blob=sample('hello-world.txt'), msg=b'hello world'.hex()),
                  dict(id='movements-demo.txt', mode='movements', ad='', blob=sample('movements-demo.txt')),
                  dict(id='rehearsal-demo.txt', mode='rehearsal', ad=b'rehearsal-demo'.hex(), blob=sample('rehearsal-demo.txt'))]

os.makedirs(os.path.dirname(OUT), exist_ok=True)
json.dump(out, open(OUT, 'w'), indent=1)
print('wrote', OUT, '| block_cipher', len(out['block_cipher']), '| formats', len(out['formats']),
      '| app keys', len(out['app_keys']), '| app blobs', len(out['app_blobs']), '| samples', len(out['samples']))
