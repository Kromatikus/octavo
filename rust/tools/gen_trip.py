#!/usr/bin/env python3 -B
"""Generate straight-line triplet mixes (integer mod 256) for simd.rs.

Each coefficient uses a minimal signed-digit form (digits in {-1,0,1}, positions 0..7, mod 256), so
e.g. 254 = -2 costs one subtract instead of seven adds. Terms are summed as balanced trees.
Output: crates/octavo-core/src/trip_gen.rs (include!-ed by simd.rs). Public constants only."""
import itertools, sys
sys.dont_write_bytecode = True
T=[[[5,1,1],[2,3,1],[5,5,2]],[[1,3,1],[3,5,2],[3,2,1]],[[2,1,1],[1,3,1],[3,3,2]],[[3,3,1],[2,5,3],[1,3,2]],[[1,1,1],[1,3,2],[3,2,3]],[[2,1,3],[3,1,3],[1,2,5]]]
TI=[[[1,3,254],[1,5,253],[251,236,13]],[[1,255,1],[3,254,1],[247,7,252]],[[3,1,254],[1,1,255],[250,253,5]],[[1,253,4],[255,5,249],[1,250,9]],[[5,255,255],[3,0,255],[249,1,2]],[[255,1,0],[244,7,3],[5,253,255]]]
best={}
for digs in itertools.product((-1,0,1),repeat=8):
    v=sum(d<<i for i,d in enumerate(digs))%256
    cost=(sum(d!=0 for d in digs), max([i for i,d in enumerate(digs) if d]+[0]), sum(d<0 for d in digs))
    if v not in best or cost<best[v][0]:
        best[v]=(cost,digs)
def tree(op, xs):
    while len(xs)>1:
        n=[]
        for i in range(0,len(xs)-1,2): n.append(f"{op}({xs[i]}, {xs[i+1]})")
        if len(xs)%2: n.append(xs[-1])
        xs=n
    return xs[0]
def gen(name, JM):
    out=[f"#[inline]\n#[target_feature(enable = \"gfni,avx512f,avx512bw,avx512vl,avx512vbmi,ssse3,sse4.1\")]\nfn {name}(c: &mut CV) {{"]
    for j,m in JM:
        out.append(f"    {{ // rows {j}..{j+2}: {m}")
        need=[0,0,0]
        for i in range(3):
            for k in range(3):
                if m[i][k]:
                    d=best[m[i][k]][1]; need[k]=max(need[k],max(p for p in range(8) if d[p]))
        for k in range(3):
            out.append(f"        let d{k}_0 = c[{j+k}];")
            for p in range(1,need[k]+1):
                out.append(f"        let d{k}_{p} = v_add(d{k}_{p-1}, d{k}_{p-1});")
        for i in range(3):
            P=[];N=[]
            for k in range(3):
                if m[i][k]:
                    for p,dg in enumerate(best[m[i][k]][1]):
                        if dg==1 or (dg==-1 and p==7): P.append(f"d{k}_{p}")
                        elif dg==-1: N.append(f"d{k}_{p}")
            if not P: P=["v_zero()"]
            e=tree("v_add",P)
            if N: e=f"v_sub({e}, {tree('v_add',N)})"
            out.append(f"        let o{i} = {e};")
        out.append(f"        c[{j}] = o0;\n        c[{j+1}] = o1;\n        c[{j+2}] = o2;\n    }}")
    out.append("}\n")
    return "\n".join(out)
# self-check of the signed-digit forms
for v in range(256):
    assert sum(d<<i for i,d in enumerate(best[v][1]))%256==v
src="// @generated by tools/gen_trip.py -- do not edit. Integer (mod 256) triplet mixes, straight-line;\n// coefficients are public constants (no data-dependent anything).\n"
src+=gen("trip_fwd",[(j,T[j]) for j in range(6)])
src+=gen("trip_inv",[(j,TI[j]) for j in reversed(range(6))])
open(sys.argv[1] if len(sys.argv)>1 else "crates/octavo-core/src/trip_gen.rs","w").write(src)
