/// One keyed S-box in collapsed affine-inversion-affine form, plus its inverse.
#[derive(Clone, Copy, Debug)]
pub struct KeyedSbox {
    pub m_in: Mat8,
    pub c_in: u8,
    pub m_out: Mat8,
    pub c_out: u8,
    m_in_inv: Mat8,
    m_out_inv: Mat8,
}

impl KeyedSbox {
    /// From the Python parameters (A1, b1, A2, b2) given as row masks.
    pub fn new(a1_rows: &[u8; 8], b1: u8, a2_rows: &[u8; 8], b2: u8) -> KeyedSbox {
        let a1 = Mat8::from_rows(*a1_rows);
        let a2 = Mat8::from_rows(*a2_rows);
        let m_in = SM4_A.mul(&a1);
        let c_in = SM4_A.apply(b1) ^ SM4_C;
        let m_out = a2.mul(&SM4_A);
        let c_out = a2.apply(SM4_C) ^ b2;
        KeyedSbox { m_in, c_in, m_out, c_out, m_in_inv: m_in.inverse(), m_out_inv: m_out.inverse() }
    }

    /// Constant-time forward S-box.
    #[inline(always)]
    pub fn fwd(&self, x: u8) -> u8 {
        self.m_out.apply(gf::inv(self.m_in.apply(x) ^ self.c_in)) ^ self.c_out
    }

    /// Constant-time inverse S-box.
    #[inline(always)]
    pub fn inv(&self, y: u8) -> u8 {
        self.m_in_inv.apply(gf::inv(self.m_out_inv.apply(y ^ self.c_out)) ^ self.c_in)
    }

    /// (Min^-1, cin, Mout^-1, cout) for the bitsliced inverse.
    pub(crate) fn inverse_parts(&self) -> (&Mat8, u8, &Mat8, u8) {
        (&self.m_in_inv, self.c_in, &self.m_out_inv, self.c_out)
    }

    /// Full 256-entry table (schedule-time only: used for the S2 != S rule and the table backend).
    pub fn table(&self) -> [u8; 256] {
        let mut t = [0u8; 256];
        for x in 0..256 {
            t[x] = self.fwd(x as u8);
        }
        t
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn sm4_decomposition() {
        for x in 0..256usize {
            let y = SM4_A.apply(gf::inv(SM4_A.apply(x as u8) ^ SM4_C)) ^ SM4_C;
            assert_eq!(y, SM4_SBOX[x], "x={x}");
        }
    }
}
