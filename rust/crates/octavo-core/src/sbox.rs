//! Keyed S-boxes S(x) = A2·SM4[A1·x ⊕ b1] ⊕ b2.
//!
//! The SM4 S-box itself is affine-equivalent to field inversion in GF(2^8)/0x1F5:
//!     SM4[x] = A·inv(A·x ⊕ 0xD3) ⊕ 0xD3,  A = rows [a7 4f 9e 3d 7a f4 e9 d3].
//! So every keyed S-box collapses to   S(x) = Mout·inv(Min·x ⊕ cin) ⊕ cout
//! with Min = A·A1, cin = A·b1 ⊕ C, Mout = A2·A, cout = A2·C ⊕ b2.
//! Evaluating that with masked-XOR matrices and a ladder x^254 is table-free and branch-free
//! (constant time). This is also exactly the shape GFNI's GF2P8AFFINEINVQB computes (modulo a
//! field isomorphism, since GFNI uses 0x11B), which is why the phase-2 GFNI backend fits here.

