#!/usr/bin/env python3
"""Independent Python reference for the SN3C/ 0x1C AEAD (N3-PMAC-SIV), written from
the construction notes in rust/src/aead.rs, using python/octavo_n3.py as the block
cipher. The tag is a PMAC over a uniquely length-prefixed transcript, not the
fix1 CMAC/S2V. Writes vectors/aead_fix2_vectors.txt: seed nonce ad msg blob
(hex, '-' = empty). Homemade; for real secrets use AES-GCM-SIV, age, or libsodium.
"""
import hashlib, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "python"))
import octavo_n3 as n3

B = 128
AEAD_FMT = 0x1C
PRE = b"SN3C/"
POLY = (1 << 19) | (1 << 6) | (1 << 1) | 1

def dbl(x: bytes) -> bytes:
    v = int.from_bytes(x, "big") << 1
    if v >> 1024:
        v = (v ^ (1 << 1024)) ^ POLY
    return v.to_bytes(B, "big")

def xor(a, b):
    return bytes(p ^ q for p, q in zip(a, b))

def ntz(i: int) -> int:
    # number of trailing zeros of a positive integer
    return (i & -i).bit_length() - 1

def u64le(n: int) -> bytes:
    return n.to_bytes(8, "little")

def kdf(seed, label):
    return b"".join(
        hashlib.sha256(PRE + bytes([AEAD_FMT]) + b"AEAD-KDF" + label + c.to_bytes(4, "big") + seed).digest()
        for c in range(4)
    )

class Aead:
    def __init__(self, seed):
        self.mac = n3.Cipher(kdf(seed, b"M"), b"SN3C/AEAD-MAC\0\0\0")
        self.enc = n3.Cipher(kdf(seed, b"E"), b"SN3C/AEAD-ENC\0\0\0")
        L = self.mac.encrypt_block(bytes(B))
        self.Lpow = [L]
        for _ in range(64):
            self.Lpow.append(dbl(self.Lpow[-1]))
        self.k_full = xor(L, self.Lpow[1])  # 3L
        self.k_part = xor(L, self.Lpow[2])  # 5L

    def delta(self, k: int) -> bytes:
        # Closed form, independent of the Rust recurrence:
        # Δ_k = XOR_{i=1}^{k+1} L[ntz(i)+1]
        d = bytes(B)
        for i in range(1, k + 2):
            d = xor(d, self.Lpow[ntz(i) + 1])
        return d

    def pmac(self, data: bytes) -> bytes:
        assert data, "transcript is never empty"
        blocks = [data[i:i + B] for i in range(0, len(data), B)]
        sigma = bytes(B)
        for k, blk in enumerate(blocks[:-1]):
            sigma = xor(sigma, self.mac.encrypt_block(xor(blk, self.delta(k))))
        last = blocks[-1]
        n = len(blocks) - 1
        if len(last) == B:
            x = xor(xor(last, self.delta(n)), self.k_full)
        else:
            x = xor(xor(last + b"\x80" + bytes(B - len(last) - 1), self.delta(n)), self.k_part)
        return self.mac.encrypt_block(xor(sigma, x))

    def transcript(self, ad, nonce, msg) -> bytes:
        h = PRE + bytes([AEAD_FMT])
        return (
            u64le(len(h)) + h
            + u64le(len(ad)) + ad
            + u64le(16) + nonce
            + u64le(len(msg)) + msg
        )

    def ctr(self, tag, data):
        out = bytearray()
        for i in range(0, len(data), B):
            blk = tag + b"SN3C/CTR" + bytes(B - 32 - 8 - 8) + (i // B).to_bytes(8, "little")
            out += xor(data[i:i + B], self.enc.encrypt_block(blk))
        return bytes(out)

    def seal(self, nonce, ad, msg):
        tag = self.pmac(self.transcript(ad, nonce, msg))[:32]
        return PRE + bytes([AEAD_FMT]) + nonce + tag + self.ctr(tag, msg)

if __name__ == "__main__":
    h = lambda b: b.hex() if b else "-"
    seed = bytes((i * 29 + 7) & 255 for i in range(128))
    seed2 = hashlib.sha256(b"kat2").digest() * 4
    cases = [
        (seed, b"nonce-0000000001", b"", b""),
        (seed, b"nonce-0000000001", b"ad", b"hello octavo"),
        (seed, b"nonce-0000000002", bytes(range(130)), bytes(range(128))),
        (seed2, bytes(16), b"x" * 7, bytes((i * 7) & 255 for i in range(300))),
        # exactly one full transcript block with empty AD: 54 + 74 = 128
        (seed, b"nonce-0000000001", b"", bytes((i * 3) & 255 for i in range(74))),
        # two full transcript blocks: 54 + 202 = 256
        (seed, b"nonce-0000000003", b"ad-x", bytes(range(202))),
    ]
    lines = ["# seed nonce ad msg blob  (SN3C/ 0x1C AEAD PMAC-SIV, fix2; generated by tools/aead_ref.py)"]
